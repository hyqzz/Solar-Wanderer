/**
 * 月球地心黄道 J2000 坐标（km）。ELP2000 完整截断版，精度 < 0.1°。
 * 使用 Delaunay 基本引数 D/M/M'/F 直接组合周期项。
 */
export function moonGeocentricELP2000(jdTT) {
  const T = centuriesTT(jdTT);

  // Delaunay 基本引数（度）
  const D = 297.8501921 + 445267.1114034 * T - 0.0018819 * T * T;
  const M = 357.5291092 + 35999.0502909 * T - 0.0001536 * T * T;
  const Mp = 134.9633964 + 477198.8675055 * T + 0.0087414 * T * T;
  const F = 93.2720950 + 483202.0175233 * T - 0.0036539 * T * T;

  // 月球平黄经（度，瞬时平黄道）
  let lambda = 218.3164591 + 481267.88134236 * T;

  // 叠加黄经周期项
  for (const [d, m, mp, f, amp] of L_TERMS) {
    lambda += amp * sinD(d * D + m * M + mp * Mp + f * F);
  }

  // 黄纬（度）
  let beta = 0;
  for (const [d, m, mp, f, amp] of B_TERMS) {
    beta += amp * sinD(d * D + m * M + mp * Mp + f * F);
  }

  // 距离（km）
  let r = 385000.56;
  for (const [d, m, mp, f, amp] of R_TERMS) {
    r += amp * cosD(d * D + m * M + mp * Mp + f * F);
  }

  // 转回 J2000 黄道（减去黄经总岁差）
  lambda -= PRECESSION_DEG_PER_CENTURY * T;

  const cl = cosD(lambda), sl = sinD(lambda);
  const cb = cosD(beta), sb = sinD(beta);
  return { x: r * cb * cl, y: r * cb * sl, z: r * sb };
}
